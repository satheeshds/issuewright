// Package scaffold generates the starting point for a new plugin.
//
// The claim in the design is "another kind of runner is one package plus one
// Register call". This package is what makes that claim executable: it writes the
// package, the registration, a table test driven by the stub brain and the fake
// GitHub client, and prints the docs row to paste.
package scaffold

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// ModulePath reads the module line from a repo's go.mod.
func ModulePath(dir string) (string, error) {
	raw, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return "", fmt.Errorf("read go.mod in %s: %w", dir, err)
	}
	m := regexp.MustCompile(`(?m)^module\s+(\S+)`).FindStringSubmatch(string(raw))
	if len(m) != 2 {
		return "", fmt.Errorf("no module directive in %s/go.mod", dir)
	}
	return m[1], nil
}

// New returns file path → contents for a new workflow or brain plugin.
func New(kind, name, dir string) (map[string]string, error) {
	if !regexp.MustCompile(`^[a-z][a-z0-9-]*$`).MatchString(name) {
		return nil, fmt.Errorf("plugin name %q must be lowercase letters, digits and dashes", name)
	}
	pkg := strings.ReplaceAll(name, "-", "")
	mod, err := ModulePath(dir)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	switch kind {
	case "workflow":
		base := filepath.Join(dir, "internal", "workflow", pkg)
		out[filepath.Join(base, pkg+".go")] = workflowSrc(mod, pkg, name)
		out[filepath.Join(base, pkg+"_test.go")] = workflowTestSrc(pkg, name)
	case "brain":
		base := filepath.Join(dir, "internal", "brain", pkg)
		out[filepath.Join(base, pkg+".go")] = brainSrc(mod, pkg, name)
		out[filepath.Join(base, pkg+"_test.go")] = brainTestSrc(pkg, name)
	default:
		return nil, fmt.Errorf("unknown plugin kind %q (workflow|brain)", kind)
	}
	return out, nil
}

// DocsRow is the line to add to the plugin table in docs/README.md.
func DocsRow(kind, name string) string {
	switch kind {
	case "workflow":
		return fmt.Sprintf("| `%s` | TODO: which events start it | TODO: yes/no |", name)
	case "brain":
		return fmt.Sprintf("| `%s` | TODO: the CLI it wraps |", name)
	}
	return ""
}

func workflowSrc(mod, pkg, name string) string {
	return fill(workflowTmpl, pkg, name)
}

func workflowTestSrc(pkg, name string) string {
	return fill(workflowTestTmpl, pkg, name)
}

func brainSrc(mod, pkg, name string) string {
	return fill(brainTmpl, pkg, name)
}

func brainTestSrc(pkg, name string) string {
	return fill(brainTestTmpl, pkg, name)
}

// fill substitutes the two placeholders the templates use. Replacer instead of
// Sprintf because the generated code is full of % characters.
func fill(tmpl, pkg, name string) string {
	return strings.NewReplacer("@@PKG@@", pkg, "@@NAME@@", name).Replace(tmpl)
}

const workflowTmpl = `// Package @@PKG@@ is a workflow: it decides what a run may do.
//
// Generated by ` + "`issuewright new workflow @@NAME@@`" + `. Fill in the trigger, the
// permissions, and the prompt; everything else (worktree, brain, checks,
// publishing) is already handled by the engine.
package @@PKG@@

import (
	"github.com/satheeshds/issuewright/internal/brain"
	"github.com/satheeshds/issuewright/internal/workflow"
)

// Engine implements workflow.Workflow.
type Engine struct{}

// New returns the workflow.
func New() *Engine { return &Engine{} }

func init() { workflow.Register(New()) }

// Name implements workflow.Workflow.
func (e *Engine) Name() string { return "@@NAME@@" }

// Triggers implements workflow.Workflow. Pick the events that should start it:
// workflow.IssueAssigned, workflow.IssueLabel, workflow.PROpened,
// workflow.CommentMention.
func (e *Engine) Triggers() []workflow.Trigger {
	return []workflow.Trigger{{Kind: workflow.IssueAssigned}}
}

// Perms implements workflow.Workflow. Claim only what you need: the engine
// refuses anything not claimed here, whatever the prompt says.
func (e *Engine) Perms() workflow.Perms {
	return workflow.Perms{Comment: true, Label: true, Checks: true}
}

// Prompt implements workflow.Workflow.
func (e *Engine) Prompt(job workflow.Job) (brain.Spec, error) {
	if job.Number == 0 {
		return brain.Spec{}, workflow.ErrNoJob
	}
	return brain.Spec{
		Prompt:  "TODO: describe the job for #" + job.Title + " of " + job.Repo,
		Workdir: job.Workdir,
	}, nil
}
`

