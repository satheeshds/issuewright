const brainTmpl = `// Package @@PKG@@ is a brain driver: it runs one agent CLI.
//
// Generated by ` + "`issuewright new brain @@NAME@@`" + `. Fill in the argument mapping and
// the capabilities; the engine adapts to whatever you claim.
package @@PKG@@

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os/exec"
	"time"

	"github.com/satheeshds/issuewright/internal/brain"
)

// Driver runs the @@NAME@@ CLI.
type Driver struct {
	Bin string
}

// New returns the driver.
func New() *Driver { return &Driver{Bin: "@@NAME@@"} }

func init() { brain.Register(New()) }

// Name implements brain.Driver.
func (d *Driver) Name() string { return "@@NAME@@" }

// Caps implements brain.Driver. Claim only what the CLI really supports: a false
// Resume makes the engine pass a flag the CLI does not understand.
func (d *Driver) Caps() brain.Caps {
	return brain.Caps{}
}

// Run implements brain.Driver.
func (d *Driver) Run(ctx context.Context, spec brain.Spec, log io.Writer) (brain.Result, error) {
	bin := d.Bin
	if bin == "" {
		bin = "@@NAME@@"
	}
	runCtx := ctx
	if spec.Timeout > 0 {
		var cancel context.CancelFunc
		runCtx, cancel = context.WithTimeout(ctx, spec.Timeout)
		defer cancel()
	}
	// TODO: map spec (Prompt, Model, Thinking, Continue) onto the CLI's flags.
	cmd := exec.CommandContext(runCtx, bin, spec.Prompt)
	cmd.Dir = spec.Workdir
	cmd.Stdout = log
	cmd.Stderr = log

	start := time.Now()
	res := brain.Result{Driver: d.Name(), Model: spec.Model}
	err := cmd.Run()
	res.Duration = time.Since(start)
	var exitErr *exec.ExitError
	switch {
	case err == nil:
	case errors.As(err, &exitErr):
		res.ExitCode = exitErr.ExitCode()
	default:
		return res, fmt.Errorf("%s: %w", d.Name(), err)
	}
	if res.ExitCode != 0 {
		return res, fmt.Errorf("%s: exit %d", d.Name(), res.ExitCode)
	}
	return res, nil
}
`

